def get_crop_agronomy(crop_name: str) -> dict:
    """Returns comprehensive agronomic profile for a given crop name."""
    c_clean = crop_name.lower().strip().replace(" ", "_")
    for k, v in EXPANDED_PLANT_AGRONOMY.items():
        if k in c_clean or c_clean in k:
            return v
    return DEFAULT_AGRONOMY
